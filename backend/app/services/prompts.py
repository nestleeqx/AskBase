# Тон ответов из настроек бота: (название в админке, указание модели).
# Факты от тона не зависят — меняется только подача
TONES = {
    "neutral": ("Нейтральный", ""),
    "friendly": (
        "Дружелюбный",
        "тёплый и дружелюбный. Начни ответ с короткой доброжелательной фразы (например, "
        "«С радостью подскажу!» или «Хороший вопрос!») и закончи одним уместным эмодзи.",
    ),
    "formal": (
        "Официальный",
        "официальный и сдержанный: полные предложения, без разговорных слов, восклицаний и эмодзи.",
    ),
    "brief": ("Коротко", "максимально короткий: одно предложение, только главный факт."),
}


def answer_system(tone: str = "neutral") -> str:
    rule = TONES.get(tone, TONES["neutral"])[1]
    return f"{ANSWER_SYSTEM}\n\nСтиль ответа: {rule}" if rule else ANSWER_SYSTEM


def _speaker(role: str) -> str:
    return {"user": "Клиент", "operator": "Администратор"}.get(role, "Бот")


def condense_prompt(history: list[tuple[str, str]], question: str) -> str:
    lines = ["История диалога:"]
    lines += [f"{_speaker(role)}: {text}" for role, text in history]
    lines += ["", f"Вопрос клиента: {question}"]
    return "\n".join(lines)


def answer_prompt(
    fragments: list[tuple[str, str]],
    history: list[tuple[str, str]],
    question: str,
    query: str,
) -> str:
    """fragments — пары (заголовок: документ и раздел, текст фрагмента)."""
    lines: list[str] = []
    if history:
        lines += ["История диалога:"]
        lines += [f"{_speaker(role)}: {text}" for role, text in history]
        lines += [""]
    lines += ["Фрагменты документов клиники:", ""]
    for i, (title, text) in enumerate(fragments, 1):
        lines += [f"[{i}] {title}", text, ""]
    lines += [f"Вопрос клиента: {question}"]
    if query != question:
        lines += [f"Смысл вопроса с учётом диалога: {query}"]
    return "\n".join(lines)
